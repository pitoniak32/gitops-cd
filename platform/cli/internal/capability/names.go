package capability

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// CheckNames reports generated names that would collide across capabilities: Kargo projects
// kargo-<cap>-<app> (ADR 0029) and Application names <cap>-<app>-<target>. It reads only app names and
// each app.yml's stages.*.targets keys, so it runs over every capability even when lint checks a subset.
// Stricter than render (which counts only Argo CD deploys, per region): a gha deploy that switches to
// Argo CD later must not collide either. Unreadable files are skipped (their capability's lint reports
// them). step (may be nil) is called after each capability.
func CheckNames(root string, step func(capName string)) []Diag {
	type source struct {
		owner string // cap/app or cap/app/target: one name from one place counts once
		at    Diag
	}
	projects := map[string][]source{}
	apps := map[string][]source{}
	add := func(m map[string][]source, name, owner string, at Diag) {
		for _, s := range m[name] {
			if s.owner == owner {
				return
			}
		}
		m[name] = append(m[name], source{owner, at})
	}
	for _, c := range Names(root) {
		files, _ := filepath.Glob(filepath.Join(root, "capabilities", c, "apps", "*", "app.y*ml"))
		sort.Strings(files)
		for _, p := range files {
			if ext := filepath.Ext(p); ext != ".yml" && ext != ".yaml" {
				continue
			}
			a := filepath.Base(filepath.Dir(p))
			rel := filepath.ToSlash(filepath.Join("capabilities", c, "apps", a, filepath.Base(p)))
			add(projects, "kargo-"+c+"-"+a, c+"/"+a, Diag{File: rel, Line: 1, Col: 1})
			b, err := os.ReadFile(p)
			if err != nil {
				continue
			}
			doc, d := parse(rel, b)
			if d != nil {
				continue
			}
			for _, st := range pairs(get(doc, "stages")) {
				for _, t := range pairs(get(st.v, "targets")) {
					add(apps, c+"-"+a+"-"+t.k, c+"/"+a+"/"+t.k, Diag{File: rel, Line: t.key.Line, Col: t.key.Column})
				}
			}
		}
		if step != nil {
			step(c)
		}
	}
	var diags []Diag
	report := func(m map[string][]source, what string) {
		for name, ss := range m {
			if len(ss) < 2 {
				continue
			}
			for _, s := range ss {
				var others []string
				for _, o := range ss {
					if o.owner != s.owner {
						others = append(others, o.at.File)
					}
				}
				d := s.at
				d.Msg = fmt.Sprintf("%s %s is also generated by %s: rename a capability or app", what, name, strings.Join(others, ", "))
				diags = append(diags, d)
			}
		}
	}
	report(projects, "Kargo project")
	report(apps, "Application name")
	return SortDedupe(diags)
}
