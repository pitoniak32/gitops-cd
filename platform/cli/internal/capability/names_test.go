package capability

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeFile(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestCheckNames(t *testing.T) {
	t.Parallel()
	r := t.TempDir()
	// kargo-a-b-c from cap a-b app c and cap a app b-c
	writeFile(t, r, "capabilities/a-b/apps/c/app.yml", "stages:\n  dev:\n    targets:\n      x-y: {}\n")
	writeFile(t, r, "capabilities/a/apps/b-c/app.yml", "stages:\n  dev:\n    targets:\n      x-y: {}\n")
	// Application a-b-c-x-y also from cap a app b, target c-x-y; the same target in two stages counts once
	writeFile(t, r, "capabilities/a/apps/b/app.yml", "stages:\n  dev:\n    targets:\n      c-x-y: {}\n  prod:\n    targets:\n      c-x-y: {}\n")
	writeFile(t, r, "capabilities/ok/apps/one/app.yml", "stages: {dev: {targets: {t: {}}}}\n")
	writeFile(t, r, "capabilities/broken/apps/z/app.yml", "a: [\n")

	var got, stepped []string
	for _, d := range CheckNames(r, func(c string) { stepped = append(stepped, c) }) {
		got = append(got, d.String())
	}
	out := strings.Join(got, "\n")
	for _, want := range []string{
		"capabilities/a-b/apps/c/app.yml:1:1: Kargo project kargo-a-b-c is also generated by capabilities/a/apps/b-c/app.yml",
		"capabilities/a/apps/b-c/app.yml:1:1: Kargo project kargo-a-b-c is also generated by capabilities/a-b/apps/c/app.yml",
		"capabilities/a-b/apps/c/app.yml:4:7: Application name a-b-c-x-y is also generated by capabilities/a/apps/b-c/app.yml, capabilities/a/apps/b/app.yml",
		"capabilities/a/apps/b/app.yml:4:7: Application name a-b-c-x-y",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in\n%s", want, out)
		}
	}
	if strings.Contains(out, "capabilities/ok/") || strings.Contains(out, "broken") {
		t.Errorf("unexpected diag:\n%s", out)
	}
	if strings.Join(stepped, ",") != "a,a-b,broken,ok" {
		t.Errorf("steps: %v", stepped)
	}
	n := 0
	for _, l := range got {
		if strings.HasPrefix(l, "capabilities/a/apps/b/app.yml:") {
			n++
		}
	}
	if n != 1 {
		t.Errorf("same target in two stages must report once, got %d:\n%s", n, out)
	}
}
