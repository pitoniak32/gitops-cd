package capability

import (
	"strings"
)

// SchemaMarkdown renders docs as reference pages, one per kind, keyed "<kind>.md": a field table with
// nested fields flattened to dotted paths (dict keys as placeholders, list items as []) and each
// field's fixture example linked relative to docs/reference/.
func SchemaMarkdown(docs []SchemaDoc) map[string]string {
	out := map[string]string{}
	for _, d := range docs {
		var b strings.Builder
		b.WriteString("<!-- generated by gcd docs; do not edit -->\n# " + d.Kind + "\n\n")
		b.WriteString("File: `" + d.File + "`\n\n" + mdText(d.Desc) + "\n\n")
		b.WriteString("| Field | Type | Required | Values | Platforms | Description | Example |\n")
		b.WriteString("|---|---|---|---|---|---|---|\n")
		for _, f := range d.Fields {
			mdRows(&b, "", f)
		}
		out[d.Kind+".md"] = b.String()
	}
	return out
}

// mdRows writes f's row (path = prefix + its name) and the rows under it.
func mdRows(b *strings.Builder, prefix string, f FieldDoc) {
	name := f.Name
	if name == "*" {
		name = "<KEY>"
	}
	p := name
	if prefix != "" {
		p = prefix + "." + name
	}
	mdRow(b, p, f)
	for _, c := range f.Fields {
		mdRows(b, p, c)
	}
	if f.Elem == nil {
		return
	}
	e := *f.Elem
	switch f.Type {
	case "dict":
		e.Name = dictKey(f.Name)
		mdRows(b, p, e)
	case "list":
		mdRow(b, p+"[]", e)
		for _, c := range e.Fields {
			mdRows(b, p+"[]", c)
		}
	}
}

func mdRow(b *strings.Builder, path string, f FieldDoc) {
	req := ""
	if f.Required {
		req = "yes"
	}
	vals := ""
	switch {
	case len(f.Enum) > 0:
		vals = strings.Join(f.Enum, ", ")
	case f.Pattern != "":
		vals = "`" + f.Pattern + "`"
	}
	cells := []string{"`" + path + "`", f.Type, req, vals, strings.Join(f.Platforms, ", "), mdText(f.Desc), mdExample(f.Example)}
	for i, c := range cells {
		cells[i] = mdCell(c)
	}
	b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
}

// mdExample turns "<FixtureRoot>/<file>:<line>" into a link from docs/reference/.
func mdExample(ex string) string {
	i := strings.LastIndex(ex, ":")
	if i < 0 {
		return ""
	}
	file, line := ex[:i], ex[i+1:]
	return "[`" + strings.TrimPrefix(file, exampleDir) + ":" + line + "`](../../" + file + "#L" + line + ")"
}

func mdCell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

// mdText escapes prose for GitHub markdown: <owner> would otherwise be an HTML tag.
func mdText(s string) string {
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(s)
}
