// Package regions loads the region registry and writes region-derived config.
package regions

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// Config is the output of `cue export ... -e regionConfig`.
type Config struct {
	Regions         []string          `json:"regions"`
	KeycloakClients []json.RawMessage `json:"keycloakClients"`
	KargoArgocdURLs map[string]string `json:"kargoArgocdUrls"`
}

const (
	regionsFile = "platform/cluster/regions"
	realmFile   = "platform/infrastructure/keycloak/manifests/kargo-realm.json"
	kargoValues = "platform/infrastructure/kargo/values.yaml"
)

// Load runs cue in platform/render to get the region config.
func Load(root string) (Config, error) {
	var c Config
	cmd := exec.Command("cue", "export", "clusters.cue", "regions.cue", "-e", "regionConfig", "--out", "json")
	cmd.Dir = filepath.Join(root, "platform", "render")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return c, fmt.Errorf("cue export: %w: %s", err, stderr.String())
	}
	if err := json.Unmarshal(out, &c); err != nil {
		return c, fmt.Errorf("parse cue output: %w", err)
	}
	return c, nil
}

// List reads platform/cluster/regions, skipping comment and blank lines.
func List(root string) ([]string, error) {
	f, err := os.Open(filepath.Join(root, regionsFile))
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		l := strings.TrimSpace(sc.Text())
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		out = append(out, l)
	}
	return out, sc.Err()
}

// Write regenerates the three region-derived files.
func Write(root string, c Config) error {
	var b strings.Builder
	b.WriteString("# one regional kind cluster per line (kind cluster = region-<name>); read by up, down, infra\n")
	b.WriteString("# GENERATED by mise run regions from platform/render/clusters.cue: never edit\n")
	for _, r := range c.Regions {
		b.WriteString(r + "\n")
	}
	if err := os.WriteFile(filepath.Join(root, regionsFile), []byte(b.String()), 0o644); err != nil {
		return err
	}
	if err := writeRealm(filepath.Join(root, realmFile), c.KeycloakClients); err != nil {
		return err
	}
	return writeKargoValues(filepath.Join(root, kargoValues), c)
}

var argocdClient = regexp.MustCompile(`^argocd-`)

func compact(raw json.RawMessage) ([]byte, error) {
	var b bytes.Buffer
	if err := json.Compact(&b, raw); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// writeRealm replaces argocd-* clients, preserving key order (jq-style output).
func writeRealm(path string, gen []json.RawMessage) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	if t, err := dec.Token(); err != nil || t != json.Delim('{') {
		return fmt.Errorf("%s: not a JSON object", path)
	}
	var buf bytes.Buffer
	buf.WriteByte('{')
	first := true
	for dec.More() {
		kt, err := dec.Token()
		if err != nil {
			return err
		}
		key := kt.(string)
		var raw json.RawMessage
		if err := dec.Decode(&raw); err != nil {
			return err
		}
		if key == "clients" {
			var clients []json.RawMessage
			if err := json.Unmarshal(raw, &clients); err != nil {
				return err
			}
			var keep []json.RawMessage
			for _, cl := range clients {
				var id struct {
					ClientID string `json:"clientId"`
				}
				if err := json.Unmarshal(cl, &id); err != nil {
					return err
				}
				if !argocdClient.MatchString(id.ClientID) {
					keep = append(keep, cl)
				}
			}
			keep = append(keep, gen...)
			raw, err = json.Marshal(keep)
			if err != nil {
				return err
			}
		}
		cr, err := compact(raw)
		if err != nil {
			return err
		}
		kb, _ := json.Marshal(key)
		if !first {
			buf.WriteByte(',')
		}
		first = false
		buf.Write(kb)
		buf.WriteByte(':')
		buf.Write(cr)
	}
	buf.WriteByte('}')
	var out bytes.Buffer
	if err := json.Indent(&out, buf.Bytes(), "", "  "); err != nil {
		return err
	}
	out.WriteByte('\n')
	return os.WriteFile(path, out.Bytes(), 0o644)
}

func mapping(n *yaml.Node, key string) *yaml.Node {
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

// writeKargoValues sets api.argocd.urls (plain block-style scalars) keeping comments.
func writeKargoValues(path string, c Config) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return err
	}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return fmt.Errorf("%s: empty or non-mapping document", path)
	}
	api := mapping(doc.Content[0], "api")
	if api == nil {
		return fmt.Errorf("%s: no api", path)
	}
	argocd := mapping(api, "argocd")
	if argocd == nil {
		return fmt.Errorf("%s: no api.argocd", path)
	}
	urls := mapping(argocd, "urls")
	if urls == nil {
		return fmt.Errorf("%s: no api.argocd.urls", path)
	}
	// jq-sorted key order, matching yq env() of `jq -c`
	keys := make([]string, 0, len(c.KargoArgocdURLs))
	for k := range c.KargoArgocdURLs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	urls.Content = nil
	urls.Kind = yaml.MappingNode
	urls.Style = 0
	for _, k := range keys {
		urls.Content = append(urls.Content,
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: k},
			&yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: c.KargoArgocdURLs[k]})
	}
	var out bytes.Buffer
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return err
	}
	enc.Close()
	return os.WriteFile(path, out.Bytes(), 0o644)
}
